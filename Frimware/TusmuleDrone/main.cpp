#include <Arduino.h>

#include "RTCManager.h"
#include "BLEManager.h"
#include "BLEProtocol.h"
#include "DroneStateMachine.h"

void setup()
{
    Serial.begin(115200);

    delay(1000);

    Serial.println();
    Serial.println("====================================");
    Serial.println("      TUSMULE DRONE V1.0");
    Serial.println("====================================");
    Serial.println();

    //------------------------------------------------------
    // RTC
    //------------------------------------------------------

    RTC.begin();

    //------------------------------------------------------
    // BLE
    //------------------------------------------------------

    BLE.begin();

    //------------------------------------------------------
    // Protocol
    //------------------------------------------------------

    Protocol.begin();

    //------------------------------------------------------
    // State Machine
    //------------------------------------------------------

    DroneFSM.begin();

    DroneFSM.start();

    Serial.println();
    Serial.println("System Ready");
}

void loop()
{
    //------------------------------------------------------
    // BLE
    //------------------------------------------------------

    BLE.update();

    //------------------------------------------------------
    // State Machine
    //------------------------------------------------------

    DroneFSM.update();

    delay(10);
}